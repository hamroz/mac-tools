// MARK: - Pasteboard

/// Every item on the clipboard with every representation it offers, so a run
/// can put back exactly what was there (rich text, images, files…).
struct PasteboardSnapshot: Equatable {
    var items: [[String: Data]]
}

@MainActor
protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    func restore(_ snapshot: PasteboardSnapshot)
    func clear()
    func string() -> String?
    /// A transient write is marked so clipboard managers skip it.
    func write(_ string: String, transient: Bool)
}

@MainActor
final class SystemPasteboard: PasteboardAccess {
    private let pasteboard: NSPasteboard
    /// Conventions from nspasteboard.org that clipboard history apps honor.
    private static let markers = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }

    var changeCount: Int { pasteboard.changeCount }

    func snapshot() -> PasteboardSnapshot {
        PasteboardSnapshot(items: (pasteboard.pasteboardItems ?? []).map { item in
            var representations: [String: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { representations[type.rawValue] = data }
            }
            return representations
        })
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        let items = snapshot.items.filter { !$0.isEmpty }.map { representations in
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    func clear() { pasteboard.clearContents() }

    func string() -> String? { pasteboard.string(forType: .string) }

    func write(_ string: String, transient: Bool) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        if transient {
            for marker in Self.markers { item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
        }
        pasteboard.writeObjects([item])
    }
}

// MARK: - System access

enum CommandKey {
    case copy
    case paste
}

/// The parts of macOS a run touches besides the clipboard; faked in tests.
@MainActor
protocol SelectionEnvironment {
    var isAccessibilityTrusted: Bool { get }
    var isSecureInputEnabled: Bool { get }
    func frontmostAppPID() -> pid_t?
    /// The focused element's selection through Accessibility, when the app exposes
    /// it, and whether that element can be edited (nil when unknown).
    func accessibilitySelection() -> (text: String, isEditable: Bool?)?
    /// Waits until the hotkey's modifier keys are up, so ⌘C isn't read as ⌥⌘C.
    func waitForModifierRelease(timeout: TimeInterval) async
    func post(_ key: CommandKey)
}

@MainActor
struct SystemSelectionEnvironment: SelectionEnvironment {
    var isAccessibilityTrusted: Bool { AccessibilityPermission.shared.refresh() }

    var isSecureInputEnabled: Bool { IsSecureEventInputEnabled() }

    func frontmostAppPID() -> pid_t? { NSWorkspace.shared.frontmostApplication?.processIdentifier }

    func accessibilitySelection() -> (text: String, isEditable: Bool?)? {
        let systemWide = AXUIElementCreateSystemWide()
        // A hung app must not stall the run; ⌘C is the fallback anyway.
        AXUIElementSetMessagingTimeout(systemWide, 0.25)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return nil }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, 0.25)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &value) == .success,
              let text = value as? String else { return nil }
        return (text, Self.isEditable(element))
    }

    /// Only clear cases count as read-only, a web page or a label, since a wrong
    /// "read-only" would stop pastes that work.
    private static func isEditable(_ element: AXUIElement) -> Bool? {
        func attribute(_ name: String) -> CFTypeRef? {
            var value: CFTypeRef?
            return AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success ? value : nil
        }
        let role = attribute(kAXRoleAttribute) as? String ?? ""
        if [kAXTextFieldRole, kAXTextAreaRole, kAXComboBoxRole, "AXSearchField"].contains(role) { return true }
        var settable: DarwinBoolean = false
        if AXUIElementIsAttributeSettable(element, kAXValueAttribute as CFString, &settable) == .success, settable.boolValue {
            return true
        }
        // Web content inside an editable region (Chrome, Safari) names its editable ancestor.
        if attribute("AXEditableAncestor") != nil { return true }
        if role == "AXWebArea" || role == kAXStaticTextRole { return false }
        return nil
    }

    func waitForModifierRelease(timeout: TimeInterval) async {
        let modifiers: CGEventFlags = [.maskCommand, .maskControl, .maskAlternate, .maskShift]
        let deadline = Date().addingTimeInterval(timeout)
        while !CGEventSource.flagsState(.combinedSessionState).intersection(modifiers).isEmpty, Date() < deadline {
            await uncancellableSleep(0.01)
        }
    }

    func post(_ key: CommandKey) {
        let keyCode = CGKeyCode(key == .copy ? kVK_ANSI_C : kVK_ANSI_V)
        let source = CGEventSource(stateID: .hidSystemState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: isDown) else { continue }
            // Explicit flags: only ⌘, whatever else is still held down.
            event.flags = .maskCommand
            event.post(tap: .cghidEventTap)
        }
    }
}

/// Sleeps even when the task is cancelled. Clipboard work, once started, must
/// finish so the original contents are always put back.
@MainActor
func uncancellableSleep(_ seconds: TimeInterval) async {
    await withCheckedContinuation { continuation in
        DispatchQueue.main.asyncAfter(deadline: .now() + seconds) { continuation.resume() }
    }
}

// MARK: - Capture and replace

struct CapturedSelection: Equatable {
    enum Method: Equatable {
        case accessibility
        case copy
    }

    let text: String
    let appPID: pid_t?
    let method: Method
    /// false when the selection is known to be read-only, such as text on a web page.
    var isEditable: Bool? = nil
}

/// Reads the selection in the frontmost app and writes a result over it.
/// Both directions leave the clipboard as it was.
@MainActor
final class TextSelectionBridge {
    struct Timing {
        var modifierRelease: TimeInterval = 0.4
        /// How long the app gets to answer ⌘C.
        var copyTimeout: TimeInterval = 0.6
        var pollInterval: TimeInterval = 0.015
        /// How long the app gets to read the clipboard after ⌘V before it is restored.
        var pasteSettle: TimeInterval = 0.4
    }

    private let pasteboard: PasteboardAccess
    private let environment: SelectionEnvironment
    var timing: Timing

    init(pasteboard: PasteboardAccess, environment: SelectionEnvironment, timing: Timing = Timing()) {
        self.pasteboard = pasteboard
        self.environment = environment
        self.timing = timing
    }

    var isAccessibilityTrusted: Bool { environment.isAccessibilityTrusted }

    func capture() async throws -> CapturedSelection {
        guard environment.isAccessibilityTrusted else { throw TextAssistantError.accessibilityNotTrusted }
        guard !environment.isSecureInputEnabled else { throw TextAssistantError.secureInput }
        let pid = environment.frontmostAppPID()

        if let selection = environment.accessibilitySelection(), !selection.text.isBlank {
            return CapturedSelection(text: selection.text, appPID: pid, method: .accessibility, isEditable: selection.isEditable)
        }

        await environment.waitForModifierRelease(timeout: timing.modifierRelease)
        let snapshot = pasteboard.snapshot()
        // Clearing first makes "the app copied something" detectable even when
        // the selection equals what was already on the clipboard.
        pasteboard.clear()
        let marker = pasteboard.changeCount
        environment.post(.copy)
        var copied: String?
        let deadline = Date().addingTimeInterval(timing.copyTimeout)
        while Date() < deadline {
            await uncancellableSleep(timing.pollInterval)
            if pasteboard.changeCount != marker {
                copied = pasteboard.string()
                break
            }
        }
        pasteboard.restore(snapshot)
        try Task.checkCancellation()

        guard let copied, !copied.isBlank else { throw TextAssistantError.noSelection }
        return CapturedSelection(text: copied, appPID: pid, method: .copy)
    }

    func replace(_ selection: CapturedSelection, with text: String) async throws {
        guard environment.isAccessibilityTrusted else { throw TextAssistantError.accessibilityNotTrusted }
        if let pid = selection.appPID, environment.frontmostAppPID() != pid { throw TextAssistantError.focusChanged }

        await environment.waitForModifierRelease(timeout: timing.modifierRelease)
        let snapshot = pasteboard.snapshot()
        pasteboard.write(text, transient: true)
        let written = pasteboard.changeCount
        environment.post(.paste)
        await uncancellableSleep(timing.pasteSettle)
        // If the user copied something in the meantime, keep theirs.
        if pasteboard.changeCount == written { pasteboard.restore(snapshot) }
    }

    /// The fallback when a result can't be pasted: leave it for ⌘V.
    func leaveOnClipboard(_ text: String) {
        pasteboard.write(text, transient: false)
    }
}

private extension String {
    var isBlank: Bool { trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
}
